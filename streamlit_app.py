# ---------- finding wines in the database ----------------------------------

def find_best_bottle(wine_type, max_price, dish):
    """Return the best-rated real wine of one type that costs max_price or less (or None).

    For a dessert we look for a sweet wine (e.g. 'Late Harvest'),
    for all other dishes we skip sweet wines.
    """
    # AI-generated (Claude) - see AI_USE_LOG.md entry 7
    # we build the SQL query step by step
    # the ? marks are placeholders - pandas fills in the values from 'params'
    # (this is safer than putting the values directly into the text,
    # because it prevents SQL injection, see week 7 database demo)
    sql = """SELECT title, variety, country, province, winery, points, price, description
             FROM wines
             WHERE variety = ? AND price <= ?"""
    params = [wine_type, max_price]

    if dish['course'] == 'dessert' and WINE_STYLES[wine_type]['color'] == 'white':
        # dessert + white grape (e.g. Riesling): the title must contain one of the sweet words
        sweet_conditions = []
        for word in SWEET_WINE_WORDS:
            sweet_conditions.append('title LIKE ?')
            params.append(f'%{word}%')
        sql += ' AND (' + ' OR '.join(sweet_conditions) + ')'
    elif dish['course'] != 'dessert':
        # savoury dish: the title must not contain any sweet word
        for word in SWEET_WINE_WORDS:
            sql += ' AND title NOT LIKE ?'
            params.append(f'%{word}%')

    # best rating first - if two wines have the same rating, the cheaper one first
    sql += ' ORDER BY points DESC, price ASC LIMIT 1'
    bottles = pd.read_sql(sql, DB, params=params)

    if len(bottles) == 0:
        return None
    return bottles.iloc[0]


def search_wines(text):
    """Return up to 20 wines whose name contains every word of the text."""
    # AI-generated (Claude) - see AI_USE_LOG.md entry 7
    # we add one condition per word: "AND title LIKE ?"
    # LIKE '%barolo%' means: the title contains 'barolo' somewhere
    # 'WHERE 1 = 1' is always true - it only lets us start every condition with AND
    sql = """SELECT title, variety, country, province, winery, points, price, description
             FROM wines WHERE 1 = 1"""
    params = []
    for word in text.split():
        sql += ' AND title LIKE ?'
        params.append(f'%{word}%')
    sql += ' ORDER BY points DESC LIMIT 20'

    return pd.read_sql(sql, DB, params=params)


def find_wine_type_in_text(text):
    """Look for a grape variety (e.g. 'Merlot') or a famous wine name (e.g. 'Barolo') in a text."""
    # AI-generated (Claude) - see AI_USE_LOG.md entry 7
    text = text.lower()

    for wine_type in WINE_TYPES:
        if wine_type.lower() in text:
            return wine_type

    for nickname in WINE_NICKNAMES:
        if nickname in text:
            return WINE_NICKNAMES[nickname]

    return None   # we did not recognise the wine


def get_vintage(title):
    """Return the year of a wine from its name, e.g. 'Nino Negri 2013 Sassorosso' -> '2013'."""
    # AI-generated (Claude) - see AI_USE_LOG.md entry 7
    for word in title.split():
        if len(word) == 4 and word.isdigit() and (word.startswith('19') or word.startswith('20')):
            return word
    return 'Non-vintage'


# ---------- finding dishes ---------------------------------------------------

def find_closest_dish(text):
    """Return the dish that fits a free text description best (or None if nothing fits)."""
    # AI-generated (Claude) - see AI_USE_LOG.md entry 7

    # if the user picked a dish from the list, we take it directly
    if text in list(DISHES['dish']):
        return DISHES[DISHES['dish'] == text].iloc[0]

    # otherwise we count for every dish how many words of the text it contains:
    # a word in the name of the dish counts 2 points, a word in the ingredients 1 point
    best_dish = None
    best_points = 0
    for index, dish in DISHES.iterrows():
        points = 0
        for word in text.lower().split():
            if len(word) < 3 or word in STOP_WORDS:
                continue
            if word in dish['dish'].lower():
                points += 2
            elif word in dish['ingredients'].lower():
                points += 1

        if points > best_points:
            best_points = points
            best_dish = dish

    return best_dish


def fits_allergies(dish, allergies, other_allergies):
    """Return True if the dish contains none of the things the user cannot eat."""
    # AI-generated (Claude) - see AI_USE_LOG.md entry 7

    # the allergens of the dish, e.g. 'gluten;lactose' -> ['gluten', 'lactose']
    # (we split the text, otherwise 'fish' would also be found inside 'shellfish')
    dish_allergens = dish['allergens'].split(';')
    for allergy in allergies:
        if allergy.lower() in dish_allergens:
            return False

    # the user's own words, e.g. 'mushrooms, garlic' -> we look for them in the ingredients
    for item in other_allergies.split(','):
        item = item.strip().lower()
        if item != '' and item in dish['ingredients'].lower():
            return False

    return True


def fits_preferences(dish, preferences, own_wish):
    """Return True if the dish fits the food preferences of the user."""
    # AI-generated (Claude) - see AI_USE_LOG.md entry 7

    # the diet: if the user chose some diets, the dish must have one of them
    allowed_diets = []
    if 'Meat dish' in preferences:
        allowed_diets.append('meat')
    if 'Fish dish' in preferences:
        allowed_diets.append('fish')
    if 'Vegetarian' in preferences:
        allowed_diets.append('vegetarian')
        allowed_diets.append('vegan')       # vegan dishes are vegetarian too
    if 'Vegan' in preferences:
        allowed_diets.append('vegan')
    if len(allowed_diets) > 0 and dish['diet'] not in allowed_diets:
        return False

    # the other wishes must all be true
    if 'High protein' in preferences and dish['protein'] < 30:
        return False
    if 'Low calorie' in preferences and dish['calories'] > 450:
        return False
    if 'Quick (under 40 min)' in preferences and dish['cooking_time'] > 40:
        return False

    # the user's own words, e.g. 'pasta' - at least one word must appear in the dish
    if own_wish.strip() != '':
        dish_text = f"{dish['dish']} {dish['ingredients']} {dish['diet']}".lower()
        found = False
        for word in own_wish.lower().split():
            if len(word) >= 3 and word not in STOP_WORDS and word in dish_text:
                found = True
        if not found:
            return False

    return True


def filter_dishes(dishes, allergies, other_allergies, preferences, own_wish):
    """Return only the dishes that fit the allergies and the preferences of the user."""
    # AI-generated (Claude) - see AI_USE_LOG.md entry 7
    kept = []
    for index, dish in dishes.iterrows():
        if fits_allergies(dish, allergies, other_allergies) and fits_preferences(dish, preferences, own_wish):
            kept.append(dish)
    return pd.DataFrame(kept)


