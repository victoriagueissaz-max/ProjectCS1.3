def save_favorite(dish, wine_type, wine_name, price, score):
    """Save one dish and wine combination in the favorites table of the database."""
    # AI-generated (Claude) - see AI_USE_LOG.md entry 7
    # this function is also called from the pop-up window, which Streamlit runs
    # separately from the rest of the page - there the connection DB of the page
    # cannot be used. So we open our own short connection just for saving.
    connection = sqlite3.connect(DATABASE_FILE)
    cursor = connection.cursor()

    # INSERT adds a new row (like in Unit07.section3)
    cursor.execute("""INSERT INTO favorites (dish_id, wine_type, wine_name, price, score, saved_on)
                      VALUES (?, ?, ?, ?, ?, ?)""",
                   (int(dish['dish_id']), wine_type, wine_name, price, int(score),
                    date.today().strftime('%d.%m.%Y')))
    # int(...) is needed because pandas gives us a special number type
    # (numpy.int64) that SQLite does not understand - int() makes it a normal number

    # commit() makes the change permanent in the database file
    connection.commit()
    connection.close()


