def ask_for_wine(key, ask_details):
    """Let the user type the name of a wine (and, if wanted, its year and producer).

    key:          a short text that makes the names of the input fields unique
    ask_details:  True = also ask for year and producer
    Returns a dictionary {'wine_type': ..., 'name': ..., 'bottle': ...} or None.
    """
    # AI-generated (Claude) - see AI_USE_LOG.md entry 7
    year = ''
    producer = ''

    if ask_details:
        # name, year and producer next to each other in one row
        col_name, col_year, col_producer = st.columns([3, 1, 2])
        with col_name:
            name = st.text_input('Name of the wine', key=f'{key}_name',
                                 placeholder='e.g. Barolo, Prosecco or Château Margaux')
        with col_year:
            year = st.text_input('Year', key=f'{key}_year', placeholder='e.g. 2016')
        with col_producer:
            producer = st.text_input('Producer', key=f'{key}_producer', placeholder='e.g. Antinori')
    else:
        name = st.text_input('Name of the wine', key=f'{key}_name',
                             placeholder='e.g. Barolo, Prosecco or Château Margaux')

    search_text = f'{name} {year} {producer}'.strip()
    if search_text == '':
        return None

    # 1) look for this exact wine in our 70,000 wine reviews
    found = search_wines(search_text)
    if len(found) > 0:
        title = st.selectbox(f'We found {len(found)} matching wines in our database. Which one is yours?',
                             found['title'], index=None, key=f'{key}_pick',
                             placeholder='Choose your bottle (optional)')
        if title is not None:
            bottle = found[found['title'] == title].iloc[0]
            return {'wine_type': bottle['variety'], 'name': bottle['title'], 'bottle': bottle}

    # 2) recognise the grape variety from the name (e.g. 'Barolo' -> Nebbiolo)
    wine_type = find_wine_type_in_text(search_text)

    # 3) if that did not work: take the most common grape of the wines we found
    if wine_type is None and len(found) > 0:
        wine_type = found['variety'].mode()[0]

    # 4) if we still do not know it, we ask the user
    if wine_type is None:
        wine_type = st.selectbox('We do not know this wine yet. Which grape or style is it?',
                                 WINE_TYPES, index=None, key=f'{key}_type',
                                 placeholder='Choose a grape variety')
        if wine_type is None:
            return None
    else:
        st.caption(f'We read this as a **{wine_type}**.')

    return {'wine_type': wine_type, 'name': search_text, 'bottle': None}


