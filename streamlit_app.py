def get_image_urls(wiki_pages):
    """Ask the Wikipedia API for the main photo of several Wikipedia articles at once.

    wiki_pages is a list of article titles, e.g. ['Risotto', 'Tiramisu'].
    Returns a dictionary {article title: web address (URL) of its photo}.
    """
    # AI-generated (Claude) - see AI_USE_LOG.md entry 6
    # the parameters tell the API what we want: the main photo ('pageimages')
    # of these articles, 800 pixels wide. The titles are separated by '|'.
    parameters = {
        'action': 'query',
        'prop': 'pageimages',
        'piprop': 'thumbnail',
        'pithumbsize': 800,
        'pilimit': 50,
        'titles': '|'.join(wiki_pages),
        'format': 'json',
    }
    # Wikipedia asks every program to say who it is (a 'User-Agent')
    headers = {'User-Agent': 'WineAndDine-StudentProject/1.0'}

    # we try up to 3 times: if Wikipedia is busy it answers with status code 429
    # ("too many requests") - then we wait 5 seconds and try again
    response = None
    for attempt in range(3):
        try:
            response = requests.get(WIKIPEDIA_API, params=parameters, headers=headers, timeout=20)
        except Exception:
            return {}     # no internet - the app then simply shows no photos

        if response.status_code == 200:       # 200 means "OK"
            break
        time.sleep(5)

    if response.status_code != 200:
        return {}         # Wikipedia did not answer - the app shows no photos

    # turn the answer into Python dictionaries and lists. It looks like:
    # {'query': {'pages': {'12345': {'title': 'Risotto', 'thumbnail': {'source': URL}}, ...}}}
    data = response.json()

    photos = {}
    for page in data['query']['pages'].values():
        if 'thumbnail' in page:
            photos[page['title']] = page['thumbnail']['source']
    return photos


def add_dish_images(dishes):
    """Add a column 'image_url' with a Wikipedia photo to the dishes table."""
    # AI-generated (Claude) - see AI_USE_LOG.md entry 6
    all_pages = list(dishes['wiki_page'])

    # the API accepts at most 50 titles per request, so we ask in groups of 30
    photos = {}
    for start in range(0, len(all_pages), 30):
        group = all_pages[start:start + 30]
        photos.update(get_image_urls(group))   # add the new photos to the dictionary
        time.sleep(1)

    # look up the photo of every dish in the dictionary ('' if there is none)
    image_urls = []
    for wiki_page in all_pages:
        image_urls.append(photos.get(wiki_page, ''))
    dishes['image_url'] = image_urls

    return dishes


def build_database():
    """Read all CSV files and write them as tables into the database file."""
    # AI-generated (Claude) - see AI_USE_LOG.md entries 2, 6 and 9
    wines = load_wines()
    dishes = pd.read_csv(os.path.join(DATA_FOLDER, 'dishes.csv'))
    pairings = pd.read_csv(os.path.join(DATA_FOLDER, 'pairings.csv'))
    wine_styles = pd.read_csv(os.path.join(DATA_FOLDER, 'wine_styles.csv'))
    kaggle_pairings = load_kaggle_pairings()

    # dishes without allergens have an empty cell - we store '' instead of "no value"
    dishes['allergens'] = dishes['allergens'].fillna('')
    dishes = add_dish_images(dishes)

    # we first write into a file with a temporary name. Only when everything
    # worked, we rename it to wine_dine.db - so if something goes wrong in the
    # middle, there is never a half-finished database
    temporary_file = DATABASE_FILE + '.building'
    if os.path.exists(temporary_file):
        os.remove(temporary_file)
    connection = sqlite3.connect(temporary_file)

    # write every table into the database
    # if_exists='replace' means: if the table already exists, overwrite it
    wines.to_sql('wines', connection, if_exists='replace', index=False)
    dishes.to_sql('dishes', connection, if_exists='replace', index=False)
    pairings.to_sql('pairings', connection, if_exists='replace', index=False)
    wine_styles.to_sql('wine_styles', connection, if_exists='replace', index=False)
    kaggle_pairings.to_sql('kaggle_pairings', connection, if_exists='replace', index=False)

    # the favorites table starts empty - users fill it by clicking "Save" in the app
    # saved_id is a number that SQLite gives every saved row automatically
    cursor = connection.cursor()
    cursor.execute("""CREATE TABLE favorites (
                          saved_id INTEGER PRIMARY KEY AUTOINCREMENT,
                          dish_id INTEGER,
                          wine_type TEXT,
                          wine_name TEXT,
                          price REAL,
                          score INTEGER,
                          saved_on TEXT
                      )""")
    connection.commit()
    connection.close()

    os.replace(temporary_file, DATABASE_FILE)   # rename: the database is ready


