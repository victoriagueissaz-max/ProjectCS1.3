# ---------- the match score and the match bar ------------------------------

def predict_match_score(wine_type, dish):
    """PLACEHOLDER for the machine learning model of our ML teammate.

    Returns how well a wine type goes with a dish, from 1 (bad) to 100 (perfect).
    dish is one row of the dishes table.

    Until the model is ready, we use simple rules:
    1. If the wine is in our pairing table for this dish, we use its score.
    2. Otherwise we compare the wine with the wines in our table for this dish:
       a wine of the same colour (red, white, ...) and a similar body
       (light, medium, full) gets a score close to theirs.
    3. Dry wines taste sour next to sweet desserts, so they lose points there.
    """
    # AI-generated (Claude) - see AI_USE_LOG.md entry 7
    # TODO (ML teammate): replace these rules with the prediction of the trained model

    # the (usually three) wines of our pairing table for this dish
    dish_pairings = PAIRINGS[PAIRINGS['dish_id'] == dish['dish_id']]

    # rule 1: the wine is in our table
    for index, pairing in dish_pairings.iterrows():
        if pairing['wine_type'] == wine_type:
            return int(pairing['score'])

    # rule 2: compare with every wine of the table and keep the best result
    my_style = WINE_STYLES[wine_type]
    best_score = 5
    for index, pairing in dish_pairings.iterrows():
        listed_style = WINE_STYLES[pairing['wine_type']]
        score = pairing['score']

        if listed_style['color'] == my_style['color']:
            score = score - 20      # same colour: a bit worse than the real pairing
        else:
            score = score - 50      # different colour: much worse

        # 10 points less for every step of body difference (light / medium / full)
        score = score - 10 * abs(listed_style['body'] - my_style['body'])

        if score > best_score:
            best_score = score

    # rule 3: dry wine with a sweet dessert
    if dish['course'] == 'dessert' and my_style['color'] != 'sweet':
        best_score = best_score - 25

    # the score must stay between 5 and 100
    return int(max(best_score, 5))


def get_match_color(score):
    """Return the colour of the match bar: dark green for a perfect match, orange for no match."""
    # AI-generated (Claude) - see AI_USE_LOG.md entry 7
